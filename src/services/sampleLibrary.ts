function buildTrack(
  partial: Omit<TrackRecord, "pinyinInitial" | "diagFlags"> & {
    pinyinInitial?: string;
  }
): TrackRecord {
  const track: TrackRecord = {
    ...partial,
    pinyinInitial:
      partial.pinyinInitial ??
      computePinyinInitial(partial.albumArtist || partial.artist || partial.title),
    diagFlags: [],
  };
  track.diagFlags = detectDiagnosticFlags(track);
  return track;
}

